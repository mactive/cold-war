def parse(raw, faction, prefix):
    result = []
    for n, line in enumerate(raw.strip().splitlines(), 1):
        name, kind, cost, op, atk, defense, rarity, effect, history = line.split('|')
        result.append(dict(id=f'{prefix}-{n:02}', faction=faction, name=name, type=kind,
                           cost=int(cost), operation_cost=None if op == '-' else int(op),
                           attack=None if atk == '-' else int(atk), defense=None if defense == '-' else int(defense),
                           rarity=rarity, effect=effect, historical_anchor=history,
                           fictional=('原创架空' in history), alternate_timeline=('延续线' in history)))
    return result

